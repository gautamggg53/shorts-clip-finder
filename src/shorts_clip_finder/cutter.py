"""Build and run ffmpeg commands that cut the selected clips.

The same command builder feeds both ``--export-clips`` and the ``cut_clips.sh`` script, so
the script always reproduces exactly what the tool would run.
"""

from __future__ import annotations

import shlex
import subprocess
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from .export import clip_basename, clip_srt
from .media import MediaError, MediaInfo, require
from .models import Clip

VERTICAL_FILTER = "scale=1080:1920:force_original_aspect_ratio=increase,crop=1080:1920,setsar=1"
CAPTION_STYLE = (
    "FontName=DejaVu Sans,FontSize=13,Bold=1,PrimaryColour=&H00FFFFFF,OutlineColour=&H00000000,"
    "BorderStyle=1,Outline=2,Shadow=0,Alignment=2,MarginV=70"
)


@dataclass(frozen=True)
class CutOptions:
    mode: str = "copy"  # "copy" (fast, keyframe-aligned) or "exact" (re-encode)
    vertical: bool = False
    burn_captions: bool = False
    caption_words: int = 4
    crf: int = 20
    preset: str = "veryfast"

    @property
    def reencode(self) -> bool:
        return self.mode == "exact" or self.vertical or self.burn_captions


def output_suffix(source: Path, info: MediaInfo, opts: CutOptions) -> str:
    if not opts.reencode:
        return source.suffix or ".mkv"
    return ".mp4" if info.has_video else ".m4a"


def build_command(
    source: Path,
    clip: Clip,
    out_name: str,
    info: MediaInfo,
    opts: CutOptions,
    srt_name: str | None = None,
) -> list[str]:
    """ffmpeg argv for one clip. Paths in the output are relative to the clips folder."""
    if (opts.vertical or opts.burn_captions) and not info.has_video:
        raise MediaError("--vertical and --burn-captions need a video input")
    cmd = [
        "ffmpeg",
        "-nostdin",
        "-y",
        "-v",
        "error",
        "-ss",
        f"{clip.start:.3f}",
        "-i",
        str(source),
        "-t",
        f"{clip.duration:.3f}",
    ]
    if not opts.reencode:
        return [
            *cmd,
            "-map",
            "0:v:0?",
            "-map",
            "0:a:0?",
            "-c",
            "copy",
            "-avoid_negative_ts",
            "make_zero",
            out_name,
        ]
    if not info.has_video:
        return [*cmd, "-vn", "-c:a", "aac", "-b:a", "160k", out_name]
    filters = []
    if opts.vertical:
        filters.append(VERTICAL_FILTER)
    if opts.burn_captions:
        if not srt_name:
            raise ValueError("burn_captions needs an SRT file name")
        filters.append(f"subtitles={srt_name}:force_style='{CAPTION_STYLE}'")
    cmd += ["-map", "0:v:0", "-map", "0:a:0?"]
    if filters:
        cmd += ["-vf", ",".join(filters)]
    return [
        *cmd,
        "-c:v",
        "libx264",
        "-preset",
        opts.preset,
        "-crf",
        str(opts.crf),
        "-pix_fmt",
        "yuv420p",
        "-c:a",
        "aac",
        "-b:a",
        "160k",
        "-movflags",
        "+faststart",
        out_name,
    ]


@dataclass
class PlannedCut:
    clip: Clip
    output: str
    srt: str
    argv: list[str]


def plan_cuts(
    source: Path, clips: Sequence[Clip], info: MediaInfo, opts: CutOptions
) -> list[PlannedCut]:
    source = source.resolve()
    plans = []
    for clip in clips:
        base = clip_basename(clip)
        out = base + output_suffix(source, info, opts)
        srt = base + ".srt"
        argv = build_command(
            source, clip, out, info, opts, srt_name=srt if opts.burn_captions else None
        )
        plans.append(PlannedCut(clip, out, srt, argv))
    return plans


def write_caption_files(plans: Sequence[PlannedCut], clips_dir: Path, caption_words: int) -> None:
    clips_dir.mkdir(parents=True, exist_ok=True)
    for p in plans:
        (clips_dir / p.srt).write_text(clip_srt(p.clip, max_words=caption_words), encoding="utf-8")


def cut_script(plans: Sequence[PlannedCut]) -> str:
    lines = [
        "#!/bin/sh",
        "# Generated by shorts-clip-finder. Re-run to cut the clips with ffmpeg.",
        "set -e",
        'cd "$(dirname "$0")"',
        "mkdir -p clips",
        "cd clips",
    ]
    for p in plans:
        lines.append(f"# {p.clip.rank}. {p.clip.title} ({p.clip.duration:.1f}s)")
        lines.append(shlex.join(p.argv))
    return "\n".join(lines) + "\n"


def run_cuts(plans: Sequence[PlannedCut], clips_dir: Path) -> list[Path]:
    require("ffmpeg")
    clips_dir.mkdir(parents=True, exist_ok=True)
    done = []
    for p in plans:
        res = subprocess.run(p.argv, cwd=clips_dir, capture_output=True, text=True)
        if res.returncode != 0:
            raise MediaError(f"ffmpeg failed for clip {p.clip.rank}: {res.stderr.strip()}")
        done.append(clips_dir / p.output)
    return done
